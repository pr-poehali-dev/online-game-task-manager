-- Исправляем путь к папке "Быстрое обновление" для сервера C4: пользователь указал реальный путь
-- на хостинге со строчной буквы (/patch), а в базе он был записан с заглавной (/Patch) — Linux
-- различает регистр в путях файловой системы, поэтому это была ФАКТИЧЕСКИ другая (несуществующая
-- для реальных файлов) папка. Из-за этого сверка (action=launcher_sync) и заливка через приложение
-- не видели файлы, которые пользователь заливал вручную по FTP в настоящую папку /patch.
UPDATE servers
SET launcher_fast_dir = '/var/www/era/test_updater/C4/patch',
    launcher_fast_xml = '/var/www/era/test_updater/C4/patch/files.xml'
WHERE id = 'c4x1';
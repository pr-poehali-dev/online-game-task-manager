-- Нужна, чтобы дорабатывать документ по уточнениям сотрудника («добавь три позиции»,
-- «пересчитай с НДС») — модель получает предыдущую структуру как основу и возвращает
-- изменённую, а не сочиняет документ заново. Без хранения структуры каждое уточнение
-- порождало бы новый документ с другими данными.
-- Заполняется только у сообщений ассистента в режиме mode='document' (backend/ai/documents.py).
ALTER TABLE t_p84024572_online_game_task_man.ai_messages
    ADD COLUMN IF NOT EXISTS doc_spec JSONB;


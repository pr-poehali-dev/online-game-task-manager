-- Второй лимит сотрудника в разделе "AI" — на СУММАРНЫЙ ОБЪЁМ его файлов (в мегабайтах), в
-- дополнение к лимиту количества (users.ai_file_limit, см. db_migrations V0082). Нужен потому,
-- что количество файлов плохо отражает реальную нагрузку на хранилище: 10 видео по 150 МБ
-- занимают больше места, чем 200 небольших документов. Настраивается там же — в разделе
-- "Команда" рядом с лимитом количества (backend/admin/index.py, action=set_ai_size_limit).
-- 0 = загрузка файлов запрещена полностью.
ALTER TABLE users ADD COLUMN IF NOT EXISTS ai_size_limit_mb INTEGER NOT NULL DEFAULT 1024;

COMMENT ON COLUMN users.ai_size_limit_mb IS 'Суммарный объём файлов сотрудника в разделе "AI", МБ. Считается по тем же типам файлов, что и лимит количества (загруженные вложения и бланки). 0 — загрузка запрещена.';

-- Этап 3 плана AI_PROJECTS_PLAN.md — агентная работа ассистента с файлами проекта.
--
-- Когда ассистент отвечает, опираясь на документы проекта, он должен показывать ИСТОЧНИКИ: какие
-- именно файлы он прочитал, чтобы сотрудник мог проверить ответ. Храним их рядом с сообщением
-- отдельным полем — так источники переживают перезагрузку страницы и видны в истории переписки.
--
-- Формат: [{"fileId": 12, "fileName": "договор.pdf", "fileUrl": "https://...", "quote": "..."}]
ALTER TABLE ai_messages ADD COLUMN IF NOT EXISTS sources JSONB;

COMMENT ON COLUMN ai_messages.sources IS 'Документы проекта, на которые опирался ассистент при ответе (см. AI_PROJECTS_PLAN.md, этап 3).';

-- Шаги, которые ассистент выполнил, отвечая (искал по проекту, читал файл) — показываются в
-- интерфейсе под ответом, чтобы работа агента была прозрачной, а не "чёрным ящиком".
-- Формат: [{"tool": "search_project_files", "arg": "сроки поставки", "found": 3}]
ALTER TABLE ai_messages ADD COLUMN IF NOT EXISTS agent_steps JSONB;

COMMENT ON COLUMN ai_messages.agent_steps IS 'Шаги агента при подготовке ответа: какие инструменты вызывал и с какими параметрами.';

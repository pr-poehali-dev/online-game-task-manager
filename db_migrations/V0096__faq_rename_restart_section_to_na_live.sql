-- Переименование раздела «К рестарту» → «На лайв» в базе знаний (FAQ).
--
-- Само название в интерфейсе уже изменено, но тексты статей хранятся в БД и продолжали
-- описывать раздел старым именем — сотрудник читал бы инструкцию про пункт меню, которого
-- больше нет.
--
-- Замена строковая, по вхождению подстроки: правим и вопросы, и ответы. Внутренний
-- идентификатор раздела (restart) не затрагивается — это только видимый текст.
-- Формулировка «статус деплоя "Можно заливать на лайв"» НЕ трогается: это отдельная
-- сущность (статус, а не раздел), она сохраняет своё название.

UPDATE faq_items
SET question = REPLACE(question, 'К рестарту', 'На лайв')
WHERE question LIKE '%К рестарту%';

UPDATE faq_items
SET answer = REPLACE(answer, 'К рестарту', 'На лайв')
WHERE answer LIKE '%К рестарту%';


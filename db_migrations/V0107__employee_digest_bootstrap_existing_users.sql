-- Бутстрап для уже существующих сотрудников на момент введения дайджеста (V0106): точка отсчёта
-- "новых" событий — момент релиза фичи, а не история аккаунта. Без этой строки первая проверка
-- у каждого сотрудника создала бы состояние сама (см. backend/digest/index.py, action=check),
-- но с тем же NOW() — эта миграция просто делает это заранее и одним запросом для всех разом.
INSERT INTO employee_digest_state (user_id, last_ack_at)
SELECT id, now() FROM users
ON CONFLICT (user_id) DO NOTHING;

-- Выдаём новую привилегию 'patch_edit' (редактирование раздела "Патчи": загрузка/удаление
-- файлов и папок, создание/изменение/удаление записей внутри .dat-файлов) владельцу проекта
-- (id=1, new_era_l2) — по требованию пользователя это право по умолчанию не должно доставаться
-- автоматически всем администраторам (в отличие от остальных привилегий), а быть только у
-- владельца, пока сам он явно не выдаст его кому-то ещё через раздел "Команда".
UPDATE users
SET permissions = COALESCE(permissions, '{}'::jsonb) || '{"patch_edit": true}'::jsonb,
    updated_at = NOW()
WHERE id = 1;

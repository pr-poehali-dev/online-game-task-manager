-- ЕДИНСТВЕННЫЙ лимит сотрудника на файлы раздела "AI" — суммарный ОБЪЁМ в мегабайтах.
-- Количество файлов плохо отражает нагрузку на хранилище (10 видео по 150 МБ весят больше, чем
-- 200 небольших документов), поэтому лимит по количеству отменён. В объём входят ВСЕ файлы
-- сотрудника: и загруженные им, и сгенерированные моделью (картинки, видео, документы).
-- Настраивается администратором в разделе "Команда" (backend/admin/index.py,
-- action=set_ai_size_limit). 0 = загрузка и генерация запрещены полностью.
ALTER TABLE users ADD COLUMN IF NOT EXISTS ai_size_limit_mb INTEGER NOT NULL DEFAULT 1024;

COMMENT ON COLUMN users.ai_size_limit_mb IS 'Суммарный объём ВСЕХ файлов сотрудника в разделе "AI", МБ (загруженные и сгенерированные). 0 — загрузка и генерация запрещены.';

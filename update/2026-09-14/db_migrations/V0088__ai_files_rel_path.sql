-- Путь файла внутри загруженной папки для раздела "AI".
--
-- Колонка нужна, когда сотрудник перетаскивает в чат целиком папку с исходниками: без неё
-- десятки файлов с именем index.ts из разных папок превращаются в неразличимую кучу, и в
-- разделе "Мои файлы" их невозможно отличить друг от друга.
--
-- rel_path — путь ВНУТРИ загруженной папки, например "src/pages/index/Ai.tsx".
-- Пустая строка = файл загружен по одному, без папки (обычное поведение).
ALTER TABLE ai_files ADD COLUMN IF NOT EXISTS rel_path TEXT NOT NULL DEFAULT '';

-- Индекс по сотруднику и пути: именно в таком порядке строится дерево "Мои файлы".
CREATE INDEX IF NOT EXISTS idx_ai_files_rel_path ON ai_files(user_id, rel_path);

COMMENT ON COLUMN ai_files.rel_path IS 'Путь файла внутри загруженной папки (src/pages/Ai.tsx). Пусто — файл загружен отдельно, вне папки.';

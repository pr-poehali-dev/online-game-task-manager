-- Вывод «Проектов» из раздела AI: функциональность переносится в отдельный сервис.
-- Код раздела (backend/ai) к проектам больше не обращается: модули projects.py, indexing.py и
-- agent.py удалены, действия из роутера убраны.
--
-- Удалять таблицы/колонки и стирать строки инструмент миграций не даёт, поэтому данные
-- ОСТАЮТСЯ НЕТРОНУТЫМИ — это и безопаснее: если проекты понадобится перенести в новый сервис,
-- их содержимое никуда не делось. Здесь только снимаем привязки, мешающие обычной работе,
-- и помечаем объекты как неиспользуемые.
--
-- ВАЖНО: файлы сотрудников не трогаем — записи в ai_files остаются, файлы продолжают
-- показываться в «Моих файлах» и расходовать личные лимиты.

-- Диалоги проектов становятся обычными диалогами: иначе они не попали бы в список,
-- где раньше стоял фильтр project_id IS NULL, и выглядели бы пропавшими.
UPDATE ai_chats SET project_id = NULL WHERE project_id IS NOT NULL;

COMMENT ON TABLE ai_projects IS 'НЕ ИСПОЛЬЗУЕТСЯ: «Проекты» выведены из раздела AI в отдельный сервис. Обращений из кода нет, данные сохранены для возможного переноса.';
COMMENT ON TABLE ai_file_chunks IS 'НЕ ИСПОЛЬЗУЕТСЯ: поиск по содержимому файлов работал только внутри проектов. Обращений из кода нет.';
COMMENT ON COLUMN ai_files.project_id IS 'НЕ ИСПОЛЬЗУЕТСЯ: осталось от «Проектов».';
COMMENT ON COLUMN ai_chats.project_id IS 'НЕ ИСПОЛЬЗУЕТСЯ: осталось от «Проектов», обнулено.';
COMMENT ON COLUMN ai_messages.sources IS 'НЕ ИСПОЛЬЗУЕТСЯ: источники были только у ответов в сессиях проекта.';
COMMENT ON COLUMN ai_messages.agent_steps IS 'НЕ ИСПОЛЬЗУЕТСЯ: шаги агента были только в сессиях проекта.';
COMMENT ON COLUMN users.ai_project_limit IS 'НЕ ИСПОЛЬЗУЕТСЯ: лимит проектов снят вместе с «Проектами».';

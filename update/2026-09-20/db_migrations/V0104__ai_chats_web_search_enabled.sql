-- Раздел "AI": персональный переключатель "Использовать веб-поиск" для каждого диалога.
-- Раньше серверный инструмент aitunnel:web_search подключался ко ВСЕМ сообщениям обычного чата
-- автоматически (см. backend/ai/generate.py) — сотрудник не мог ни увидеть, ни отключить его.
-- Теперь это явный переключатель над полем ввода (см. AiComposer.tsx), значение сохраняется per-chat
-- вместе с выбранной моделью, чтобы не сбрасываться при переключении между диалогами.
ALTER TABLE ai_chats ADD COLUMN IF NOT EXISTS web_search_enabled BOOLEAN NOT NULL DEFAULT true;

COMMENT ON COLUMN ai_chats.web_search_enabled IS 'Включён ли инструмент веб-поиска (aitunnel:web_search) для сообщений этого диалога — управляется чекбоксом над полем ввода.';
